CREATE TABLE kitchen_account (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    username varchar(40) NOT NULL UNIQUE,
    nickname varchar(60) NOT NULL,
    password_hash varchar(100) NOT NULL,
    role varchar(10) NOT NULL CHECK (role IN ('GUEST', 'ADMIN'))
);

ALTER TABLE kitchen_order ADD COLUMN account_id bigint REFERENCES kitchen_account (id);
CREATE INDEX kitchen_order_owner_idx ON kitchen_order (account_id, id DESC);

ALTER TABLE menu_item
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    ADD COLUMN image_data bytea,
    ADD COLUMN image_media_type varchar(32),
    ADD COLUMN legacy_source_key varchar(64) UNIQUE,
    ADD CONSTRAINT menu_image_pair CHECK ((image_data IS NULL) = (image_media_type IS NULL));

SELECT setval(pg_get_serial_sequence('menu_item', 'id'), greatest(999, coalesce(max(id), 0))) FROM menu_item;

CREATE TABLE favorite_dish (
    account_id bigint NOT NULL REFERENCES kitchen_account (id) ON DELETE CASCADE,
    dish_id bigint NOT NULL REFERENCES menu_item (id) ON DELETE CASCADE,
    PRIMARY KEY (account_id, dish_id)
);

CREATE TABLE kitchen_avatar (
    id integer PRIMARY KEY CHECK (id = 1),
    image_data bytea NOT NULL,
    media_type varchar(32) NOT NULL
);
